                        <h5>Dokumentasi</h5>
                        <p>SMK PGRI Wlingi adalah sebuah sekolah menengah kejuruan di Kabupaten
                            Blitar, Jawa Timur, Indonesia. SMK PGRI Wlingi membekali siswa dengan keterampilan,
                            karakter, dan pengalaman nyata. Kami mendukung lulusan agar siap kerja, berwirausaha,
                            atau melanjutkan studi.</p>
                        <h5>Sejarah SMK PGRI Wlingi</h5>
                        <p>SMK PGRI Wlingi didirikan pada 17 Juli 1987 dengan nama awalnya STM PGRI 2 Wlingi.
                            Pendiriannya dipelopori oleh Drs. Hartoyo dan Drs. Bambang Setiyono. Sekolah ini awalnya
                            menyandang status "TERCATAT" (NSS: 324051514002 dan NDS: E 21114301). Pada 20 Januari
                            1990, melalui Surat Keputusan Direktur Jenderal Pendidikan Dasar dan Menengah Nomor
                            009/C/Kep/I/1990, statusnya ditingkatkan menjadi "DIAKUI" dengan program studi Mesin
                            Tenaga/Mekanik Umum. Saat itu, Drs. Hartoyo menjabat sebagai Kepala STM PGRI 2 Wlingi
                            yang pertama.[2]SMK PGRI Wlingi memulai operasionalnya pada 21 April 1992 dengan dua program
                            studi:</p>

                        <p> Mesin Tenaga/Mekanik Umum dan Listrik Instalasi. Sekolah ini kemudian meraih jenjang
                            "DIAKUI" pada 22 Maret 1995.Pada 27 Oktober 1999, terjadi perubahan signifikan: nama sekolah
                            berganti dari STM PGRI 2 Wlingi menjadi SMK PGRI Wlingi, dan program studi bertambah menjadi
                            tiga, yaitu
                            Mekanik Umum, Listrik Instalasi, dan Mekanik Otomotip.Status akreditasi sekolah terus
                            meningkat. Pada 5 April 2002, sekolah ditetapkan
                            mendapatkan jenjang "DISAMAKAN". Puncaknya, berdasarkan Keputusan Sidang Badan
                            Akreditasi Provinsi Jawa Timur tanggal 18 Mei 2005, SMK PGRI Wlingi menerima sertifikat
                            akreditasi dengan peringkat "B" (Baik). (Perlu diketahui, proses peningkatan statusnya
                            adalah dari "TERCATAT", kemudian "DIAKUI", dan terakhir "DISAMAKAN"). Perkembangan jurusan
                            terus berlanjut. Pada 9 Maret 2007, ditambahkan Program Keahlian
                            Teknik Komputer dan Jaringan.Sejak November 2007, kepemimpinan sekolah berpindah dari Drs.
                            Hartoyo, MM kepada Drs.Bambang Setiyono, ST., M.Pd.
                        </p>
                        <p> Di bawah kepemimpinan baru, SMK PGRI Wlingi ditunjuk
                        sebagai ICT Center SMK di Kabupaten Blitar—pusat pengembangan Teknologi Informasi,
                        pengelola pemetaan sekolah (school mapping), dan pusat data SMK se-Kabupaten Blitar.
                        Prestasi akreditasi tertinggi diraih pada 30 Oktober 2010, dengan penetapan peringkat
                        "A" (Sangat Baik) untuk Program Keahlian Teknik Pemesinan, Teknik Kendaraan Ringan,
                        Teknik Instalasi Listrik, dan Teknik Komputer dan Jaringan, yang berlaku hingga tahun
                        pelajaran 2015/2016.Peran SMK PGRI Wlingi sebagai ICT Center juga menempatkannya sebagai SUB
                        KAMPUS PVB Pens. ITS Surabaya, melalui kerja sama antara SEAMOLEC dan PENS ITS Surabaya,
                        dimulai
                        pada tahun pelajaran 2010/2011. Komitmen terhadap mutu ditegaskan dengan adopsi Sistem
                        Manajemen Mutu ISO 9001:2008 versi IWA 2 pada 5 Oktober 2011.Dalam beberapa tahun
                        berikutnya, program studi keahlian terus berkembang:Tahun 2013: Ditambahkan Rekayasa
                        Perangkat Lunak (RPL) dan Teknik Kecantikan Kulit dan
                        Rambut (TKKR).Tahun 2019: Ditambahkan Teknik Alat Berat (TAB).
                        Dua tahun kemudian (sekitar 2021): Ditambahkan Desain Komunikasi Visual (DKV) untuk
                        menyesuaikan dengan tuntutan perkembangan zaman.</p>
