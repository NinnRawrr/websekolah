                <h3><b>Visi dan Misi</b></h3>
                <hr>
                <p>Visi SMK PGRI Wlingi adalah Mewujudkan SMK PGRI WLINGI - BLITAR Yang Mandiri dan Berwawasan
                    Global,
                    Mampu Menghasilkan Lulusan Yang Unggul Dalam Teknologi, Profesional dan Berjiwa Kewirausahaan,
                    Berbudaya serta Berakhlak Mulia. Sedangkan misi SMK PGRI Wlingi adalah Yang pertama,
                    Mengembangkan
                    Sistem Pembelajaran Yang Terstandar, Sesuai Dengan Kompetensi Industri Dan Kewirausahaan. Yang
                    kedua, Melaksanakan Pengelolaan Lembaga Sebagai Pusat Pendidikan Dan Latihan Untuk Menghasilkan
                    Peserta Diklat Yang Mampu Berperan Dalam Skala Nasional Maupun Internasional. Yang ketiga,
                    Mewujudkan Lembaga Sebagai Pusat Pengembangan Budaya, Ilmu Pengetahuan Dan Teknologi Serta
                    Ketrampilan Untuk Peningkatan Potensi Sumber Daya Daerah.</p>
